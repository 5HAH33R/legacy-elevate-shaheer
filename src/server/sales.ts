import "server-only";

import { FieldValue, type DocumentData, type Firestore } from "firebase-admin/firestore";
import { z } from "zod";
import { getAdminDb } from "@/lib/firebase/admin";
import { calcItemsTotal } from "@/lib/calculations";
import type { MinorUnits } from "@/lib/money";
import { dateField, moneyField } from "@/lib/validation";
import { ApiError } from "./errors";
import { toIso, toNumber } from "./serialize";

const saleItemSchema = z.object({
  productId: z.string().trim().min(1),
  quantity: z
    .number()
    .int("Quantity must be a whole number.")
    .min(1, "Quantity must be at least 1.")
    .max(1_000_000, "Quantity is too large."),
  /** Optional price override (decimal string); defaults to the product's selling price. */
  unitPrice: moneyField("Unit price").optional(),
});

/**
 * saleId is generated by the client (crypto.randomUUID) and used as the
 * document id, which makes recording a sale idempotent: retrying the same
 * submission can never deduct stock twice (AGENTS.md sections 8–9).
 */
export const createSaleSchema = z.object({
  saleId: z.string().uuid("Invalid sale id."),
  date: dateField.optional(),
  items: z
    .array(saleItemSchema)
    .min(1, "Add at least one item.")
    .max(50, "A sale can have at most 50 items."),
});

export type CreateSaleInput = z.output<typeof createSaleSchema>;

export type SaleItem = {
  productId: string;
  /** Product name snapshot at sale time (products can be renamed later). */
  name: string;
  quantity: number;
  unitPrice: MinorUnits;
  /** Cost basis snapshot for gross profit (SPEC 5.4). */
  unitCost: MinorUnits;
};

/** SPEC.md 9.4. */
export type Sale = {
  saleId: string;
  businessId: string;
  date: string;
  items: SaleItem[];
  total: MinorUnits;
  createdAt: string | null;
};

function serializeItems(value: unknown): SaleItem[] {
  if (!Array.isArray(value)) return [];
  return value.map((raw) => {
    const item = (raw ?? {}) as Record<string, unknown>;
    return {
      productId: String(item.productId ?? ""),
      name: String(item.name ?? ""),
      quantity: toNumber(item.quantity),
      unitPrice: toNumber(item.unitPrice),
      unitCost: toNumber(item.unitCost),
    };
  });
}

function serializeSale(id: string, data: DocumentData): Sale {
  return {
    saleId: id,
    businessId: String(data.businessId ?? ""),
    date: String(data.date ?? ""),
    items: serializeItems(data.items),
    total: toNumber(data.total),
    createdAt: toIso(data.createdAt),
  };
}

/** Single-field query (no composite index); newest date first, in memory. */
export async function listSalesForBusiness(
  businessId: string,
  db: Firestore = getAdminDb(),
): Promise<Sale[]> {
  const snapshot = await db
    .collection("sales")
    .where("businessId", "==", businessId)
    .get();
  return snapshot.docs
    .map((doc) => serializeSale(doc.id, doc.data()))
    .sort((a, b) => b.date.localeCompare(a.date));
}

export type RecordSaleResult = { sale: Sale; created: boolean };

/**
 * Record a sale and deduct stock in one Firestore transaction: all product
 * reads happen before any write, stock can never go negative, and a retried
 * submission (same saleId) returns the existing sale without changing stock.
 */
export async function recordSaleForBusiness(
  businessId: string,
  input: CreateSaleInput,
  db: Firestore = getAdminDb(),
): Promise<RecordSaleResult> {
  const productIds = input.items.map((item) => item.productId);
  if (new Set(productIds).size !== productIds.length) {
    throw new ApiError(400, "Combine quantities for the same product into one row.");
  }

  const saleRef = db.collection("sales").doc(input.saleId);
  const date = input.date ?? new Date().toISOString().slice(0, 10);

  return db.runTransaction(async (tx) => {
    const existing = await tx.get(saleRef);
    if (existing.exists) {
      const data = existing.data();
      if (!data || data.businessId !== businessId) {
        throw new ApiError(409, "This sale could not be recorded. Please retry.");
      }
      return { sale: serializeSale(existing.id, data), created: false };
    }

    const productRefs = productIds.map((id) => db.collection("products").doc(id));
    const productSnaps = await Promise.all(productRefs.map((ref) => tx.get(ref)));

    const items: SaleItem[] = [];
    const deductions: { ref: (typeof productRefs)[number]; remaining: number }[] = [];
    productSnaps.forEach((snapshot, index) => {
      const data = snapshot.data();
      if (!snapshot.exists || !data || data.businessId !== businessId) {
        throw new ApiError(400, "One of the products does not belong to this business.");
      }
      const requested = input.items[index];
      const current = toNumber(data.quantity);
      const remaining = current - requested.quantity;
      if (remaining < 0) {
        throw new ApiError(
          409,
          `Not enough stock for "${String(data.name ?? "product")}" (${current} left).`,
        );
      }
      items.push({
        productId: snapshot.id,
        name: String(data.name ?? ""),
        quantity: requested.quantity,
        unitPrice: requested.unitPrice ?? toNumber(data.sellingPrice),
        unitCost: toNumber(data.unitCost),
      });
      deductions.push({ ref: productRefs[index], remaining });
    });

    const total = calcItemsTotal(items);
    for (const { ref, remaining } of deductions) {
      tx.update(ref, { quantity: remaining, updatedAt: FieldValue.serverTimestamp() });
    }
    tx.set(saleRef, {
      businessId,
      date,
      items,
      total,
      createdAt: FieldValue.serverTimestamp(),
    });
    return {
      sale: { saleId: saleRef.id, businessId, date, items, total, createdAt: null },
      created: true,
    };
  });
}
